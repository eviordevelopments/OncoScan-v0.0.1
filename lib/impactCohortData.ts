export interface QuantStats {
  count: number;
  mean: number;
  median: number;
  std: number;
  min: number;
  max: number;
  p10: number;
  p25: number;
  p50: number;
  p75: number;
  p90: number;
  iqr: number;
}

export function computePercentile(sorted: number[], p: number): number {
  if (sorted.length === 0) return 0;
  if (sorted.length === 1) return sorted[0];
  const idx = (p / 100) * (sorted.length - 1);
  const lo = Math.floor(idx);
  const hi = Math.ceil(idx);
  const weight = idx - lo;
  return Number((sorted[lo] * (1 - weight) + sorted[hi] * weight).toFixed(2));
}

export function computeQuantStats(values: number[]): QuantStats {
  if (values.length === 0) {
    return {
      count: 0,
      mean: 0,
      median: 0,
      std: 0,
      min: 0,
      max: 0,
      p10: 0,
      p25: 0,
      p50: 0,
      p75: 0,
      p90: 0,
      iqr: 0,
    };
  }
  const sorted = [...values].sort((a, b) => a - b);
  const count = sorted.length;
  const sum = sorted.reduce((acc, v) => acc + v, 0);
  const mean = sum / count;
  const variance =
    count > 1
      ? sorted.reduce((acc, v) => acc + Math.pow(v - mean, 2), 0) / (count - 1)
      : 0;
  const std = Math.sqrt(variance);
  const p10 = computePercentile(sorted, 10);
  const p25 = computePercentile(sorted, 25);
  const p50 = computePercentile(sorted, 50);
  const p75 = computePercentile(sorted, 75);
  const p90 = computePercentile(sorted, 90);
  return {
    count,
    mean: Number(mean.toFixed(2)),
    median: p50,
    std: Number(std.toFixed(2)),
    min: Number(sorted[0].toFixed(2)),
    max: Number(sorted[count - 1].toFixed(2)),
    p10,
    p25,
    p50,
    p75,
    p90,
    iqr: Number((p75 - p25).toFixed(2)),
  };
}

export function getPatientRiskFactorCount(p: CohortPatient): number {
  const hasOverweightObesity = p.bmi >= 25.0;
  const hasHtaRisk = p.repHta === "Sí" || p.pas >= 130 || p.pad >= 80;
  const hasGlycemicRisk = p.repDiabetes === "Sí" || p.glucose >= 125;
  const hasDyslipidemia = p.repDyslipidemia === "Sí";
  return (
    (hasOverweightObesity ? 1 : 0) +
    (hasHtaRisk ? 1 : 0) +
    (hasGlycemicRisk ? 1 : 0) +
    (hasDyslipidemia ? 1 : 0)
  );
}

export function hasCentralAdiposityRisk(p: CohortPatient): boolean {
  return p.sex === "H" ? p.waist > 90 : p.waist > 80;
}
